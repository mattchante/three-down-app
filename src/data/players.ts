function withAliases(base: College, extras: string[]): College {
  return {
    displayName: base.displayName,
    acceptedAnswers: [...new Set([...base.acceptedAnswers, ...extras])],
  };
}

function player(
  id: string,
  fullName: string,
  jerseyNumber: number,
  college: College,
  draftYear: number,
  currentTeam: string,
  position: Player["position"],
): Player {
  return { id, fullName, jerseyNumber, college, draftYear, currentTeam, position };
}

